import { Achievement, AchievementRule } from '../types';

/**
 * Shanyraq Hub achievements — the single place to add, remove or edit them.
 *
 * How unlocking works (`rule`):
 *   - Automatic: `{ metric, threshold }` — unlocked as soon as the member's
 *     verified activity reaches the threshold. Optional `direction` limits
 *     `events_attended` to one club direction.
 *   - Manual: `{ metric: 'manual' }` — cannot be measured from data (a speech,
 *     a race result...). A moderator awards it in the admin panel.
 *
 * Metrics (all counted from verified data only):
 *   books_completed            finished books with a 100+ char review, max one per week
 *   books_reviewed             finished books with a 100+ char review
 *   events_attended            check-ins confirmed by staff (optionally per direction)
 *   event_directions           number of different directions attended
 *   feedback_given             feedback forms sent after attended events
 *   positive_reviews_received  peer reviews with rating 4–5 received
 *   reviews_given              peer reviews written for other members
 *   forum_topics               forum topics started
 *   forum_replies              forum replies written
 *   upvotes_received           "useful" votes received on forum replies
 *   activity_streak            consecutive active days (see utils/streak.ts)
 *   activity_week_streak       consecutive weeks (Mon–Sun) with at least one activity
 *
 * Rewards are paid once per member and achievement.
 * After editing, regenerate the database seed:  npx tsx scripts/generate-seed.ts > supabase/seed.sql
 */

type AchievementDefinition = Omit<Achievement, 'isUnlocked' | 'unlockedAt' | 'currentCount' | 'requiredCount'> & {
  rule: AchievementRule;
};

const auto = (metric: AchievementRule['metric'], threshold: number, direction?: AchievementRule['direction']): AchievementRule =>
  direction ? { metric, threshold, direction } : { metric, threshold };
const manual: AchievementRule = { metric: 'manual', threshold: 1 };

