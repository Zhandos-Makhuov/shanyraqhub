/**
 * Generates supabase/seed.sql (reference data only: tiers, achievements, shop, forum categories, club directions)
 * from the same files the app uses, so the database never drifts from the UI.
 *
 *   npx tsx scripts/generate-seed.ts > supabase/seed.sql
 */
import { TIERS, SHOP_ITEMS } from '../src/data/gamification.ts';
import { ALL_ACHIEVEMENTS } from '../src/data/achievements.ts';
import { COMMUNITY_DIRECTIONS } from '../src/data/directions.ts';
import { CHAT_ROOM_DEFINITIONS } from '../src/data/chatRooms.ts';
const q = (v: unknown) => v === undefined || v === null ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const out: string[] = [];
out.push(`-- GENERATED by scripts/generate-seed.ts from src/data/gamification.ts, achievements.ts and directions.ts. Do not edit by hand.
-- Contains NO users and NO demo activity. Safe to re-run (upserts).
-- Run after the migrations: psql "$DATABASE_URL" -f supabase/seed.sql   (or: supabase db reset on a LOCAL stack)
`);
out.push('insert into public.tiers (tier, min_xp, sort_order, name_ru, name_kz, name_en, coin_multiplier) values');
out.push(Object.values(TIERS).map((t, i) =>
  `  (${q(t.tier)}, ${t.minXp}, ${i}, ${q(t.nameRu)}, ${q(t.nameKz)}, ${q(t.nameEn)}, ${(1 + t.attendanceCoinBonusPercent / 100).toFixed(2)})`).join(',\n'));
out.push(`on conflict (tier) do update set min_xp = excluded.min_xp, name_ru = excluded.name_ru, name_kz = excluded.name_kz,
  name_en = excluded.name_en, coin_multiplier = excluded.coin_multiplier;\n`);
out.push('insert into public.achievements (id, title_ru, title_kz, title_en, description_ru, description_kz, description_en, icon, category, rule, xp_reward, coin_reward) values');
out.push(ALL_ACHIEVEMENTS.map(a => {
  const rule = a.rule ?? { metric: 'manual', threshold: 1 };
  return `  (${q(a.id)}, ${q(a.titleRu)}, ${q(a.titleKz)}, ${q(a.titleEn)}, ${q(a.descriptionRu)}, ${q(a.descriptionKz)}, ${q(a.descriptionEn)}, ${q(a.icon)}, ${q(a.category)}, ${q(JSON.stringify(rule))}, ${a.xpReward}, ${a.coinReward})`;
}).join(',\n'));
out.push(`on conflict (id) do update set title_ru = excluded.title_ru, title_kz = excluded.title_kz, title_en = excluded.title_en,
  description_ru = excluded.description_ru, description_kz = excluded.description_kz, description_en = excluded.description_en,
  icon = excluded.icon, category = excluded.category, rule = excluded.rule,
  xp_reward = excluded.xp_reward, coin_reward = excluded.coin_reward;\n`);
out.push('insert into public.shop_items (id, name_ru, name_kz, name_en, description_ru, description_kz, description_en, category, rarity, price_coins, preview_url, style) values');
out.push(SHOP_ITEMS.map(s => {
  const style = JSON.stringify({ borderStyle: s.borderStyle, glowStyle: s.glowStyle, badgeTitle: s.badgeTitle });
  return `  (${q(s.id)}, ${q(s.nameRu)}, ${q(s.nameKz)}, ${q(s.nameEn)}, ${q(s.descriptionRu)}, ${q(s.descriptionKz)}, ${q(s.descriptionEn)}, ${q(s.category)}, ${q(s.rarity)}, ${s.priceCoins}, ${q(s.previewUrl)}, ${q(style)})`;
}).join(',\n'));
out.push(`on conflict (id) do update set name_ru = excluded.name_ru, name_kz = excluded.name_kz, name_en = excluded.name_en,
  description_ru = excluded.description_ru, description_kz = excluded.description_kz, description_en = excluded.description_en,
  category = excluded.category, rarity = excluded.rarity, price_coins = excluded.price_coins,
  preview_url = excluded.preview_url, style = excluded.style;\n`);
const cats: [string, string, string, string][] = [
  ['books', 'Книжная полка & Рецензии', 'Кітап сөресі & Пікірлер', 'Book Shelf & Reviews'],
  ['english', 'Speaking English Club', 'Speaking English Club', 'Speaking English Club'],
  ['arabic', 'Арабский язык & Каллиграфия', 'Араб тілі & Каллиграфия', 'Arabic & Calligraphy'],
  ['sport', 'Спорт и бег Tarlan', 'Tarlan спорт және жүгіру', 'Tarlan Sports & Running'],
  ['art', 'Арт-терапия и керамика', 'Арт-терапия және керамика', 'Art Therapy & Ceramics'],
  ['intellect', 'Интеллектуальные игры Zerde', 'Zerde зияткерлік ойындары', 'Zerde Intellectual Games'],
  ['general', 'Общие анонсы и идеи', 'Жалпы хабарландырулар', 'General Announcements & Ideas'],
];
out.push('insert into public.forum_categories (id, name_ru, name_kz, name_en, sort_order) values');
out.push(cats.map((c, i) => `  (${q(c[0])}, ${q(c[1])}, ${q(c[2])}, ${q(c[3])}, ${i})`).join(',\n'));
out.push('on conflict (id) do update set name_ru = excluded.name_ru, name_kz = excluded.name_kz, name_en = excluded.name_en, sort_order = excluded.sort_order;');
out.push('');
// Club directions. Joining requires approval (owner decision); admins can change the flag later.
// `do nothing` on conflict: texts edited by admins in the database are never overwritten.
out.push('insert into public.community_directions (id, name_ru, name_kz, name_en, short_name_ru, short_name_kz, short_name_en, description_ru, description_kz, description_en, icon, color, requires_approval, sort_order) values');
out.push(COMMUNITY_DIRECTIONS.map((d, i) =>
  `  (${q(d.id)}, ${q(d.nameRu)}, ${q(d.nameKz)}, ${q(d.nameEn)}, ${q(d.shortNameRu)}, ${q(d.shortNameKz)}, ${q(d.shortNameEn)}, ${q(d.descriptionRu)}, ${q(d.descriptionKz)}, ${q(d.descriptionEn)}, ${q(d.icon)}, ${q(d.color)}, true, ${i})`).join(',\n'));
out.push('on conflict (id) do nothing;');
// Club chat rooms (owner decision, stage 6.4): structure only, no messages. Access = min_role (RLS).
// `do nothing` on conflict: rooms edited by admins in the database are never overwritten.
out.push('');
out.push('insert into public.chat_rooms (id, title_ru, title_kz, title_en, description_ru, description_kz, description_en, direction, min_role) values');
out.push(CHAT_ROOM_DEFINITIONS.map(r =>
  `  (${q(r.id)}, ${q(r.titleRu)}, ${q(r.titleKz)}, ${q(r.titleEn)}, ${q(r.descriptionRu)}, ${q(r.descriptionKz)}, ${q(r.descriptionEn)}, ${q(r.direction)}, ${q(r.minRole)})`).join(',\n'));
out.push('on conflict (id) do nothing;');
console.log(out.join('\n'));
